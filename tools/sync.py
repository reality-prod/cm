"""Keeps the copies of shared data in this monorepo in step with their sources.

Sources (edit these):
  brand/tokens.json        colours, radii and spacing
  certs/pins.json          SPKI pins for codeberg.org's Let's Encrypt chain
  certs/roots/*.pem        Let's Encrypt root certificates

Generated (do not edit by hand):
  mobile/shared/.../ui/Tokens.kt                   from brand/tokens.json
  mobile/shared/.../ui/LogoKit.kt                  the official logo, from brand/logo-kit/*.svg
  mobile/androidApp/.../network_security_config.xml pin block, from certs/pins.json
  mobile/iosApp/project.yml                        pin block, from certs/pins.json
  mobile/androidApp/.../res/raw/*.pem             copies of certs/roots

Usage:
  python3 tools/sync.py           write every generated file
  python3 tools/sync.py --check   change nothing; exit 1 if anything is out of date (used in CI)

Needs only Python 3. Root pins are also checked with openssl when it is installed.
"""

import base64
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

TOKENS = os.path.join("brand", "tokens.json")
PINS = os.path.join("certs", "pins.json")
ROOT_CERTS = os.path.join("certs", "roots")
FONT_SRC = os.path.join("brand", "fonts")
FONT_DEST = os.path.join("mobile", "shared", "src", "commonMain", "composeResources", "font")
ROOT_COPIES = [
    os.path.join("mobile", "androidApp", "src", "main", "res", "raw"),
]

KOTLIN_LOGO = os.path.join("mobile", "shared", "src", "commonMain", "kotlin", "org", "codeberg", "mobile", "ui", "LogoKit.kt")
KOTLIN_TOKENS = os.path.join("mobile", "shared", "src", "commonMain", "kotlin", "org", "codeberg", "mobile", "ui", "Tokens.kt")
ANDROID_NSC = os.path.join("mobile", "androidApp", "src", "main", "res", "xml", "network_security_config.xml")
IOS_SPEC = os.path.join("mobile", "iosApp", "project.yml")

PIN_RE = re.compile(r"^[A-Za-z0-9+/]{43}=$")


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return f.read()


def read_or_none(rel):
    full = os.path.join(ROOT, rel)
    if not os.path.exists(full):
        return None
    return read(rel)


def fail(message):
    print(f"sync: {message}", file=sys.stderr)
    sys.exit(2)


def snake_upper(name):
    """brandBlue -> BRAND_BLUE, for C macro names."""
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name).upper()


def hex_digits(color):
    digits = color.lstrip("#").upper()
    if not re.fullmatch(r"[0-9A-F]{6}", digits):
        fail(f"not a 6-digit hex colour: {color!r}")
    return digits


def kotlin_number(value):
    """Python number -> Kotlin float literal, e.g. -1030.156 -> -1030.156f."""
    return f"{value}f"


def kotlin_logo_kit():
    """The official logo kit as Kotlin drawing data: every path, transform and fill, exactly as the SVGs define them."""
    sys.path.insert(0, os.path.join(ROOT, "tools"))
    import logokit  # noqa: E402

    def color(value, opacity=1.0):
        return f"0x{round(opacity * 255):02X}{value.lstrip('#').upper()}L"

    def number(value):
        return f"{float(value)!r}f"

    def art(name):
        logo = logokit.read_logo(os.path.join(ROOT, "brand", "logo-kit", f"codeberg-logo_{name}.svg"))
        width, height = logo["viewBox"]
        lines = [f"    val {camel(name)} = LogoArt({number(width)}, {number(height)}, listOf("]
        for part in logo["parts"]:
            fill = part["fill"]
            if fill["type"] == "solid":
                fill_code = f"LogoFill.Solid(Color({color(fill['color'])}))"
            else:
                stops = ", ".join(
                    f"{number(offset)} to Color({color(c, op)})" for offset, c, op in fill["stops"]
                )
                fill_code = (
                    f"LogoFill.Linear(listOf({stops}), {number(fill['x1'])}, {number(fill['y1'])}, "
                    f"{number(fill['x2'])}, {number(fill['y2'])})"
                )
            lines.append(
                f'        LogoPart("{part["d"]}", {number(part["scaleX"])}, {number(part["scaleY"])}, '
                f'{number(part["translateX"])}, {number(part["translateY"])}, {fill_code}),'
            )
        lines.append("    ))")
        return lines

    header = [
        "// GENERATED by tools/sync.py from brand/logo-kit/*.svg (the official Codeberg logo kit). Do not edit by hand.",
        "package org.codeberg.mobile.ui",
        "",
        "import androidx.compose.ui.graphics.Color",
        "",
        "/** One filled path of the logo. Scale and translate are the only transforms the kit uses. */",
        "class LogoPart(",
        "    val path: String,",
        "    val scaleX: Float,",
        "    val scaleY: Float,",
        "    val translateX: Float,",
        "    val translateY: Float,",
        "    val fill: LogoFill,",
        ")",
        "",
        "sealed interface LogoFill {",
        "    data class Solid(val color: Color) : LogoFill",
        "    class Linear(",
        "        val stops: List<Pair<Float, Color>>,",
        "        val x1: Float,",
        "        val y1: Float,",
        "        val x2: Float,",
        "        val y2: Float,",
        "    ) : LogoFill",
        "}",
        "",
        "/** A logo variant: its size in SVG units and its parts in drawing order. */",
        "class LogoArt(val width: Float, val height: Float, val parts: List<LogoPart>)",
        "",
        "/** The official Codeberg logo kit. Use the white variants on dark backgrounds, the blue ones on light. */",
        "object LogoKit {",
    ]
    body = []
    for name in ["icon_blue", "icon_white", "horizontal_blue", "horizontal_white", "vertical_blue", "vertical_white"]:
        body += art(name)
    return "\n".join(header + body + ["}", ""])


def camel(name):
    """icon_blue -> IconBlue"""
    return "".join(part.capitalize() for part in name.split("_"))


def kotlin_tokens(t):
    colors = t["colors"]
    radius = t["radius"]
    spacing = t["spacing"]
    lines = [
        "// GENERATED by tools/sync.py from brand/tokens.json. Do not edit by hand.",
        "package org.codeberg.mobile.ui",
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.unit.dp",
        "",
        "/** Brand colours. Names describe the role, not the screen. */",
        "object BrandColors {",
    ]
    lines += [f"    val {name} = Color(0xFF{hex_digits(value)})" for name, value in colors.items()]
    lines += ["}", "", "/** Corner radii in dp. */", "object BrandRadius {"]
    lines += [f"    val {name} = {value}.dp" for name, value in radius.items()]
    lines += ["}", "", "/** Spacing in dp. */", "object BrandSpacing {"]
    lines += [f"    val {name} = {value}.dp" for name, value in spacing.items()]
    lines += ["}", ""]
    return "\n".join(lines)


def replace_block(text, begin_marker, end_marker, body, source):
    """Replaces the lines between two marker lines. The body is written at the indentation of the begin marker."""
    lines = text.split("\n")
    begins = [i for i, line in enumerate(lines) if begin_marker in line]
    ends = [i for i, line in enumerate(lines) if end_marker in line]
    if len(begins) != 1 or len(ends) != 1 or ends[0] <= begins[0]:
        fail(f"{source}: expected one '{begin_marker}' line followed by one '{end_marker}' line")
    indent = re.match(r"\s*", lines[begins[0]]).group(0)
    new_lines = [(indent + line) if line else "" for line in body]
    return "\n".join(lines[: begins[0] + 1] + new_lines + lines[ends[0]:])


def xml_pin_body(pins):
    return [f'<pin digest="SHA-256">{p["pin"]}</pin> <!-- {p["name"]} -->' for p in pins]


def yaml_pin_body(pins):
    return [f'- SPKI-SHA256-BASE64: "{p["pin"]}"  # {p["name"]}' for p in pins]


def validate_pins(pins):
    if not pins:
        fail("certs/pins.json lists no pins")
    seen = set()
    for p in pins:
        if not PIN_RE.match(p["pin"]):
            fail(f"pin for {p['name']!r} is not a base64 SHA-256 digest")
        if p["pin"] in seen:
            fail(f"duplicate pin for {p['name']!r}")
        seen.add(p["pin"])


def root_pin_problems(pins):
    """Compares each root's pin with the root PEM itself. Returns a list of problems; empty means all good."""
    if shutil.which("openssl") is None:
        print("sync: openssl not found; skipping the root pin check", file=sys.stderr)
        return []
    problems = []
    for p in pins:
        if "root" not in p:
            continue
        pem = os.path.join(ROOT, ROOT_CERTS, p["root"])
        if not os.path.exists(pem):
            problems.append(f"missing root certificate {p['root']}")
            continue
        pubkey = subprocess.run(["openssl", "x509", "-in", pem, "-pubkey", "-noout"], capture_output=True, check=True).stdout
        der = subprocess.run(["openssl", "pkey", "-pubin", "-outform", "der"], input=pubkey, capture_output=True, check=True).stdout
        actual = base64.b64encode(hashlib.sha256(der).digest()).decode()
        if actual != p["pin"]:
            problems.append(f"pin for {p['name']} does not match {p['root']}")
    return problems


def main():
    check_only = "--check" in sys.argv[1:]
    tokens = json.loads(read(TOKENS))
    pins = json.loads(read(PINS))["pins"]
    validate_pins(pins)

    stale = []

    # Whole generated files.
    generated = {
        KOTLIN_TOKENS: kotlin_tokens(tokens),
        KOTLIN_LOGO: kotlin_logo_kit(),
    }
    # Blocks inside hand-written files.
    blocks = {
        ANDROID_NSC: replace_block(read(ANDROID_NSC), "<!-- BEGIN GENERATED PINS", "<!-- END GENERATED PINS", xml_pin_body(pins), ANDROID_NSC),
        IOS_SPEC: replace_block(read(IOS_SPEC), "# BEGIN GENERATED PINS", "# END GENERATED PINS", yaml_pin_body(pins), IOS_SPEC),
    }
    generated.update(blocks)

    for rel, new_text in generated.items():
        if not new_text.endswith("\n"):
            new_text += "\n"
        if read_or_none(rel) != new_text:
            stale.append(rel)
            if not check_only:
                with open(os.path.join(ROOT, rel), "w", encoding="utf-8") as f:
                    f.write(new_text)

    # Root certificate copies.
    for pem_name in sorted(os.listdir(os.path.join(ROOT, ROOT_CERTS))):
        if not pem_name.endswith(".pem"):
            continue
        source = os.path.join(ROOT, ROOT_CERTS, pem_name)
        with open(source, "rb") as f:
            wanted = f.read()
        for dest_dir in ROOT_COPIES:
            dest = os.path.join(ROOT, dest_dir, pem_name)
            current = None
            if os.path.exists(dest):
                with open(dest, "rb") as f:
                    current = f.read()
            if current != wanted:
                stale.append(os.path.join(dest_dir, pem_name))
                if not check_only:
                    os.makedirs(os.path.dirname(dest), exist_ok=True)
                    shutil.copyfile(source, dest)

    # Font files: brand/fonts/*.ttf is the source; the Compose resources folder gets identical copies.
    for font_name in sorted(os.listdir(os.path.join(ROOT, FONT_SRC))):
        if not font_name.endswith(".ttf"):
            continue
        with open(os.path.join(ROOT, FONT_SRC, font_name), "rb") as f:
            wanted = f.read()
        dest = os.path.join(ROOT, FONT_DEST, font_name)
        current = None
        if os.path.exists(dest):
            with open(dest, "rb") as f:
                current = f.read()
        if current != wanted:
            stale.append(os.path.join(FONT_DEST, font_name))
            if not check_only:
                os.makedirs(os.path.dirname(dest), exist_ok=True)
                shutil.copyfile(os.path.join(ROOT, FONT_SRC, font_name), dest)

    problems = root_pin_problems(pins)
    if problems:
        for problem in problems:
            print(f"sync: {problem}", file=sys.stderr)
        sys.exit(2)

    if check_only and stale:
        print("sync: these generated files are out of date. Run: make sync", file=sys.stderr)
        for rel in stale:
            print(f"  {rel}", file=sys.stderr)
        sys.exit(1)

    if stale and not check_only:
        print("sync: updated " + ", ".join(stale))
    elif not stale:
        print("sync: everything is in step")


if __name__ == "__main__":
    main()
